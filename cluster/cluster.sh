                            Submit train, monitor logs, wait, pull artifacts/checkpoints, summarize
  wait-job <job> [poll]     Poll Run:AI status and stream new logs until terminal
  job-status <job>          Show detailed Run:AI status for one job
  job-logs <job> [...]      Show Run:AI logs for one job (extra args passed to 'runai logs')
  job-delete <job>          Delete one Run:AI job
