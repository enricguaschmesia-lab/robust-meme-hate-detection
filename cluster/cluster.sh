}

main() {
    local command="${1:-}"
    [[ -n "$command" ]] || { usage; exit 1; }
    load_config
    shift
    case "$command" in
        doctor) cmd_doctor "$@" ;;
        ssh) cmd_ssh "$@" ;;
        remote-check) cmd_remote_check "$@" ;;
        runai-list) cmd_runai_list "$@" ;;
        sync-code) cmd_sync_code "$@" ;;
        pull-results) cmd_pull_results "$@" ;;
        pull-artifacts) cmd_pull_artifacts "$@" ;;
        pull-checkpoints) cmd_pull_checkpoints "$@" ;;
        build-image) cmd_build_image "$@" ;;
        push-image) cmd_push_image "$@" ;;
        submit-interactive) cmd_submit_interactive "$@" ;;
        submit-smoke) cmd_submit_smoke "$@" ;;
        submit-train) cmd_submit_train "$@" ;;
        submit-cmd) cmd_submit_cmd "$@" ;;
        run-train) cmd_run_train "$@" ;;
        wait-job) cmd_wait_job "$@" ;;
        job-status) cmd_job_status "$@" ;;
        job-logs) cmd_job_logs "$@" ;;
        job-delete) cmd_job_delete "$@" ;;
        summarize-results) cmd_summarize_results "$@" ;;
        interactive-bash) cmd_interactive_bash "$@" ;;
        -h|--help|help) usage ;;
        *) usage; die "Unknown command: $command" ;;
    esac
}

main "$@"
